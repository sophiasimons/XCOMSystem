/**
  * @brief  Function implementing the defaultTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartDefaultTask */
void StartDefaultTask(void *argument)
{
  /* init code for LWIP */
  MX_LWIP_Init();
  /* USER CODE BEGIN 5 */
  struct netconn *conn, *newconn;
  err_t err;

  // 1. Create the Semaphore for SPI DMA
  // Initial count 0 means if we try to take it, we block immediately (until SPI is done)
  SpiTxSemHandle = osSemaphoreNew(1, 0, NULL);

  // 2. Create a new TCP connection handle
  conn = netconn_new(NETCONN_TCP);

  if (conn != NULL)
  {
    // 3. Bind to Port 5000 (Host laptop connects to 192.168.1.10:5000)
    err = netconn_bind(conn, IP_ADDR_ANY, 5000);

    if (err == ERR_OK)
    {
      // 4. Put connection into LISTEN state
      netconn_listen(conn);

      while (1)
      {
        // 5. Accept a new connection (Blocking wait)
        // The task sleeps here until the Laptop connects
        err = netconn_accept(conn, &newconn);

        if (err == ERR_OK)
        {
          struct netbuf *buf;
          void *data;
          u16_t len;

          // 6. Process the incoming data stream
          while ((err = netconn_recv(newconn, &buf)) == ERR_OK)
          {
            // A netbuf might be fragmented. Iterate through the chain.
            do
            {
               // Get pointer to the data payload inside the LwIP buffer
               netbuf_data(buf, &data, &len);

               // SAFETY: Clean D-Cache to ensure DMA reads physical RAM, not old cache.
               // Even with MPU, this is a safe, low-cost guardrail.
               SCB_CleanDCache_by_Addr((uint32_t*)data, len + 32);

               // 7. Start SPI DMA Transfer (Zero Copy)
               // We pass the LwIP buffer pointer directly to SPI hardware
               if(HAL_SPI_Transmit_DMA(&hspi1, (uint8_t*)data, len) == HAL_OK)
               {
                   // 8. BLOCK here until SPI is done.
                   // The CPU yields to other tasks. DMA does the work.
                   // We wait for HAL_SPI_TxCpltCallback to release this semaphore.
                   osSemaphoreAcquire(SpiTxSemHandle, osWaitForever);
               }
               else
               {
                   // If DMA fails to start (busy?), handle error or just continue
               }

            } while (netbuf_next(buf) >= 0);

            // 9. Now that SPI is finished, we can delete the TCP buffer
            netbuf_delete(buf);
          }

          // Client disconnected
          netconn_close(newconn);
          netconn_delete(newconn);
        }
      }
    }
    else
    {
      // Bind failed (Port in use?)
      netconn_delete(conn);
    }
  }

  // Fallback if LwIP fails to start
  for(;;)
  {
    osDelay(1000);
  }
  /* USER CODE END 5 */
}

